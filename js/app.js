function titleFromName(name) {
  return name
    .replace(/\.pdf$/i, '')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\p{Ll}/gu, (c) => c.toUpperCase());
}
const fileUrl = (m) => m.file.split('/').map(encodeURIComponent).join('/');
const absUrl = (m) => new URL(fileUrl(m), location.href).href;
const shareUrl = (m) => `${location.origin}${location.pathname}#read=${encodeURIComponent(m.file)}`;
function fmtSize(b) {
  if (!b) return '';
  if (b < 1024 * 1024) return `${Math.max(1, Math.round(b / 1024))} KB`;
  return `${(b / 1024 / 1024).toFixed(1)} MB`;
}
function fmtDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  return isNaN(d) ? '' : d.toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' });
}

