function download(m) {
  // Same-origin link with the `download` attribute saves straight to the
  // device's Downloads folder (Android, desktop) or the Files app (iOS).
  const a = document.createElement('a');
  a.href = fileUrl(m);
  a.download = m.name;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
  toast(`Downloading “${m.title}”`);
}

async function share(m) {
  const url = shareUrl(m);
  const data = { title: m.title, text: `Read “${m.title}”, a free magazine`, url };
  if (navigator.share) {
    try { await navigator.share(data); return; }
    catch (e) { if (e.name === 'AbortError') return; }
  }
  try {
    await navigator.clipboard.writeText(url);
    toast('Link copied. Paste it anywhere to share.');
  } catch {
    window.prompt('Copy this link to share:', url);
  }
}

